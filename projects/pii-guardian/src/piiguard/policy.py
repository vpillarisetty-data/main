"""Turn classifications into Unity Catalog governance SQL (policy as code).

For each PII column it emits:
  1. column tags (``pii``, ``sensitivity``) so lineage, discovery and ABAC policies can use them
  2. a masking function per category, created once per schema and reused across tables
  3. ``ALTER COLUMN ... SET MASK`` binding the column to its function

Privileged groups see clear text; everyone else sees a masked form that keeps the value useful
where it safely can (last-4 of a PAN as PCI DSS allows, email domain for analytics,
deterministic SHA-256 tokens so joins still work).
"""

from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass

from piiguard.classify import ColumnClassification

_PAN_RX = r"\\b(?:\\d[ -]?){12,18}\\d\\b"
_SSN_RX = r"\\b\\d{3}-?\\d{2}-?\\d{4}\\b"
_EMAIL_RX = r"[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\\.[A-Za-z]{2,}"

MASK_EXPR: dict[str, str] = {
    "credit_card": "concat('XXXX-XXXX-XXXX-', right(regexp_replace(v, '[^0-9]', ''), 4))",
    "ssn": "concat('***-**-', right(regexp_replace(v, '[^0-9]', ''), 4))",
    "email": "regexp_replace(v, '^[^@]+', '****')",
    "phone": "concat('***-***-', right(regexp_replace(v, '[^0-9]', ''), 4))",
    "card_security_code": "NULL",
    "date_of_birth": "concat(substr(CAST(v AS STRING), 1, 4), '-**-**')",
    "free_text": (
        f"regexp_replace(regexp_replace(regexp_replace(v, '{_PAN_RX}', '[PAN]'), "
        f"'{_SSN_RX}', '[SSN]'), '{_EMAIL_RX}', '[EMAIL]')"
    ),
}
_DEFAULT_MASK = "sha2(CAST(v AS STRING), 256)"  # deterministic token keeps joins working


@dataclass(frozen=True)
class PolicyConfig:
    function_schema: str = "governance.masks"
    reader_group: str = "pii_readers"
    restricted_group: str = "pci_cardholder_data_readers"
    min_confidence: float = 0.7


def _fn_name(cfg: PolicyConfig, key: str, sensitivity: str) -> str:
    return f"{cfg.function_schema}.mask_{key}_{sensitivity}"


def _function_ddl(cfg: PolicyConfig, key: str, sensitivity: str) -> str:
    group = cfg.restricted_group if sensitivity == "restricted" else cfg.reader_group
    expr = MASK_EXPR.get(key, _DEFAULT_MASK)
    return (
        f"CREATE OR REPLACE FUNCTION {_fn_name(cfg, key, sensitivity)}(v STRING)\n"
        f"RETURNS STRING\n"
        f"COMMENT 'piiguard: masks {key} unless caller is in {group}'\n"
        f"RETURN CASE WHEN is_account_group_member('{group}') THEN v ELSE {expr} END;"
    )


def generate_policies(
    table: str, classifications: Sequence[ColumnClassification], cfg: PolicyConfig | None = None
) -> str:
    cfg = cfg or PolicyConfig()
    functions: dict[str, str] = {}
    statements: list[str] = []
    review: list[str] = []
    for c in classifications:
        if not c.is_pii:
            continue
        if c.confidence < cfg.min_confidence:
            review.append(f"--   {c.column}: {c.category}? confidence={c.confidence} ({c.evidence})")
            continue
        key = "free_text" if c.embedded else c.category
        fn = _fn_name(cfg, key, c.sensitivity)
        functions.setdefault(fn, _function_ddl(cfg, key, c.sensitivity))
        statements += [
            f"-- {c.column}: {c.category} [{c.sensitivity}] confidence={c.confidence}, {c.evidence}",
            f"ALTER TABLE {table} ALTER COLUMN `{c.column}` SET TAGS "
            f"('pii' = '{c.category}', 'sensitivity' = '{c.sensitivity}'"
            f"{', ' + chr(39) + 'pii_embedded' + chr(39) + ' = ' + chr(39) + 'true' + chr(39) if c.embedded else ''});",
            f"ALTER TABLE {table} ALTER COLUMN `{c.column}` SET MASK {fn};",
        ]
    out = [f"-- Generated by piiguard for {table}", f"CREATE SCHEMA IF NOT EXISTS {cfg.function_schema};", ""]
    out += list(functions.values()) + [""] + statements
    if review:
        out += ["", "-- NEEDS HUMAN REVIEW (below confidence threshold, not applied):", *review]
    return "\n".join(out) + "\n"
